print("  std::uint32_t msgid;")
print("  std::uint8_t crc_extra;")
print("};")
print()
print("inline constexpr CrcExtraEntry kCrcExtraTable[] = {")
for mid, extra in entries:
    print(f"    {{{mid}, {extra}}},")
print("};")
print()
print("}  // namespace mavgs::detail")
